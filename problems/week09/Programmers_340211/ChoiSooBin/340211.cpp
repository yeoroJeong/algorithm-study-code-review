/*
숙련도를 1부터 하나씩 올리면서 확인할 수도 있지만,
그때마다 모든 퍼즐의 시간을 계산하면 연산량이 너무 많아진다.

숙련도가 높아질수록 틀리는 횟수가 줄어들어
전체 소요 시간은 줄어들거나 그대로 유지된다.
따라서 제한 시간 안에 풀 수 있는 최소 숙련도를
이진 탐색으로 찾았다.

문제: [PCCP 기출문제] 2번 / 퍼즐 게임 챌린지
링크: https://school.programmers.co.kr/learn/courses/30/lessons/340212
작성자: 최수빈(sbyy77dev)
알고리즘: 이진 탐색

[문제 요약]
각 퍼즐의 난이도와 소요 시간, 전체 제한 시간이 주어진다.

숙련도가 난이도 이상이면 해당 퍼즐을 한 번에 해결한다.
숙련도가 부족하면 난이도와 숙련도의 차이만큼 틀리며,
틀릴 때마다 현재 퍼즐과 이전 퍼즐을 푸는 시간이 추가된다.

제한 시간 안에 모든 퍼즐을 해결할 수 있는
숙련도의 최솟값을 반환해야 한다.

[핵심 아이디어]
숙련도가 부족한 경우 틀리는 횟수는 diffs[i] - level이다.

한 번 틀릴 때 현재 퍼즐의 시간과 이전 퍼즐의 시간이 필요하고,
마지막에는 현재 퍼즐을 성공하는 시간도 한 번 더 필요하다.

따라서 해당 퍼즐의 소요 시간은 다음과 같다.

(diffs[i] - level) * (times[i] + times[i - 1]) + times[i]

숙련도가 충분하면 times[i]만 더하면 된다.

어떤 숙련도로 제한 시간 안에 해결할 수 있다면,
그보다 높은 숙련도로도 해결할 수 있다.
이 성질을 이용해 가능한 숙련도와 불가능한 숙련도의 경계를 찾는다.

[풀이 과정]
1. 숙련도의 탐색 범위를 1부터 100000까지로 설정한다.
2. 범위의 중간값 mid를 현재 확인할 숙련도로 정한다.
3. 첫 번째 퍼즐은 난이도가 1이므로 times[0]만 더한다.
4. 두 번째 퍼즐부터 순서대로 소요 시간을 계산한다.
   - 난이도가 mid 이하이면 해당 퍼즐의 시간만 더한다.
   - 난이도가 mid보다 높으면 실패로 추가되는 시간도 더한다.
5. 전체 시간이 limit 이하라면 mid를 정답 후보로 저장한다.
   더 작은 숙련도도 가능한지 확인하기 위해 right를 mid - 1로 바꾼다.
6. 전체 시간이 limit보다 크면 숙련도가 부족한 것이므로
   left를 mid + 1로 바꾼다.
7. left가 right보다 커질 때까지 반복하고 정답을 반환한다.

[복잡도]
- 시간 복잡도: O(N log D)
  N은 퍼즐 개수이고, D는 숙련도의 탐색 상한인 100000이다.
  이진 탐색의 각 단계에서 N개의 퍼즐을 확인한다.

- 추가 공간 복잡도: O(1)
  시간 합계와 탐색 범위를 저장하는 변수만 사용한다.
  함수의 값 전달로 발생하는 매개변수 복사는 제외한다.

[구현 시 주의할 부분]
- 마지막에 성공하는 시간
  실패 횟수만큼의 시간 외에도 현재 퍼즐을 성공하는
  times[i]를 한 번 더 더해야 한다.

- 이전 퍼즐의 시간
  이전 퍼즐을 다시 풀 때는 틀리지 않으므로,
  이전 퍼즐에서 계산했던 전체 시간이 아니라 times[i - 1]을 사용한다.

- 첫 번째 퍼즐 처리
  첫 번째 퍼즐에는 이전 퍼즐이 없다.
  diffs[0]은 1이고 숙련도도 1 이상이므로,
  times[0]을 먼저 더한 뒤 반복문을 1부터 시작했다.

- 제한 시간과 같은 경우
  제한 시간과 정확히 같아도 성공이므로 total <= limit으로 확인한다.

- 시간 합계의 자료형
  전체 시간은 int 범위를 넘을 수 있으므로 long long으로 저장한다.
  곱셈도 long long으로 계산하도록 앞에 1LL을 곱했다.

- 가능한 숙련도를 찾은 뒤
  바로 반환하면 최소 숙련도라는 보장이 없다.
  answer에 저장하고 더 작은 범위를 계속 확인해야 한다.
*/

#include <string>
#include <vector>

using namespace std;

int solution(vector<int> diffs, vector<int> times, long long limit) {
    int answer = 100000;

    int left = 1;
    int right = 100000;

    while (left <= right) {
        int mid = (left + right) / 2;

        // 첫 번째 퍼즐은 항상 한 번에 풀 수 있음
        long long total = times[0];

        for (int i = 1; i < (int)diffs.size(); i++) {
            if (diffs[i] <= mid) {
                total += times[i];
            } else {
                int fail = diffs[i] - mid;

                // 틀리는 동안 걸린 시간 + 마지막에 성공하는 시간
                total += 1LL * fail * (times[i] + times[i - 1])
                         + times[i];
            }
        }

        if (total <= limit) {
            answer = mid;

            // 가능하면 더 낮은 숙련도도 확인
            right = mid - 1;
        } else {
            // 시간이 부족하면 숙련도를 높여야 함
            left = mid + 1;
        }
    }

    return answer;
}